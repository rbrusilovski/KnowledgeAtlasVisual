import type { YtChannel, YtVideo } from "./schemas";

export interface PlaylistPage {
  items: { videoId: string; publishedAt?: string }[];
  nextPageToken?: string;
  totalResults?: number;
}

export interface SearchChannelsParams {
  q: string;
  regionCode?: string;
  relevanceLanguage?: string;
  maxResults?: number;
}

export interface SearchChannelHit {
  channelId: string;
  title: string;
  description: string;
  thumbnailUrl?: string;
}

export interface CaptionTrack {
  id: string;
  language: string;
  isAutoGenerated: boolean;
  name?: string;
}

/** Raw transport: one method per API call, no quota or caching. */
export interface RawYouTubeClient {
  readonly mode: "live" | "fixture";
  channelsList(p: { ids?: string[]; forHandle?: string; forUsername?: string }): Promise<YtChannel[]>;
  playlistItemsList(playlistId: string, pageToken?: string): Promise<PlaylistPage>;
  videosList(ids: string[]): Promise<YtVideo[]>;
  channelSectionsList(channelId: string): Promise<{ type?: string; channels: string[] }[]>;
  searchChannels(p: SearchChannelsParams): Promise<SearchChannelHit[]>;
  captionsList(videoId: string, accessToken: string): Promise<CaptionTrack[]>;
  captionsDownload(captionId: string, accessToken: string): Promise<string>;
}

export class YouTubeApiError extends Error {
  constructor(
    readonly status: number,
    readonly reason: string,
    message: string,
  ) {
    super(message);
    this.name = "YouTubeApiError";
  }
  get isQuotaExceeded() {
    return this.status === 403 && (this.reason === "quotaExceeded" || this.reason === "dailyLimitExceeded");
  }
  get retryable() {
    return (
      this.status >= 500 ||
      this.status === 429 ||
      this.status === 0 ||
      this.reason === "rateLimitExceeded" ||
      this.reason === "userRateLimitExceeded" ||
      this.reason === "backendError"
    );
  }
}
