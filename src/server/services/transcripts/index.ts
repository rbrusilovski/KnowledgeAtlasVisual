export const CORPUS_OWNER_KEY = "corpus";

// ── Access ─────────────────────────────────────────────────────────────────

export interface Viewer {
  userId: string | null;
  /** Only the viewer's own private transcripts ("My transcripts" search scope, D11). */
  onlyOwn?: boolean;
}

/** Shared-corpus transcripts: fixture transcripts only in fixture mode (never mixed into live data). */
export function corpusWhere(): Prisma.TranscriptWhereInput {
  return youtubeMode() === "fixture" ? { visibility: "CORPUS" } : { visibility: "CORPUS", source: { not: "FIXTURE" } };
}

export function visibleWhere(viewer: Viewer): Prisma.TranscriptWhereInput {
  if (viewer.onlyOwn) return viewer.userId ? { visibility: "PRIVATE", ownerUserId: viewer.userId } : { id: { in: [] } };
  return viewer.userId ? { OR: [corpusWhere(), { visibility: "PRIVATE", ownerUserId: viewer.userId }] } : corpusWhere();
}

/** SQL twin of `visibleWhere` for raw queries; `alias` is the Transcript table alias. */
export function visibleSql(viewer: Viewer, alias = "t"): Prisma.Sql {
  const t = Prisma.raw(`"${alias}"`);
  if (viewer.onlyOwn) return viewer.userId ? Prisma.sql`(${t}.visibility = 'PRIVATE' AND ${t}."ownerUserId" = ${viewer.userId})` : Prisma.sql`false`;
  const corpus = youtubeMode() === "fixture" ? Prisma.sql`${t}.visibility = 'CORPUS'` : Prisma.sql`(${t}.visibility = 'CORPUS' AND ${t}.source <> 'FIXTURE')`;
  return viewer.userId ? Prisma.sql`(${corpus} OR (${t}.visibility = 'PRIVATE' AND ${t}."ownerUserId" = ${viewer.userId}))` : corpus;
}

// ── Collection ─────────────────────────────────────────────────────────────

/** Free (no quota) transcript fetches that apply to this video. */
export async function transcriptCandidates(v: ProviderVideo): Promise<TranscriptCandidate[]> {
  const out: TranscriptCandidate[] = [];
  for (const p of PROVIDERS) out.push(...(await p.candidates(v)));
  return out;
}

export interface StoreInput {
  source: TranscriptSource;
  visibility: TranscriptVisibility;
  ownerUserId?: string;
  connectionId?: string;
  providerTrackId?: string;
  language: string;
  trackKind: TranscriptKind;
  isAutoGenerated: boolean;
  cues: Cue[];
}

export interface StoreResult {
  stored: boolean;
  chunks: number;
  transcriptId?: string;
  reason?: "unchanged" | "empty";
}

export const contentHashOf = (cues: Cue[]) => createHash("sha256").update(cues.map((c) => `${c.start}|${c.text}`).join("\n")).digest("hex");

/**
 * Upsert one transcript record keyed by (video, source, language, owner). Never touches another owner's record.
 * Unchanged content (same hash) is a no-op. CORPUS transcripts refresh shared topics; PRIVATE ones never do.
 */
export async function storeTranscript(videoId: string, input: StoreInput): Promise<StoreResult> {
  if (input.visibility === "PRIVATE" && !input.ownerUserId) throw new AppError("VALIDATION_ERROR", "Private transcripts need an owner");
  if (!input.cues.length) return { stored: false, chunks: 0, reason: "empty" };
  const ownerKey = input.visibility === "CORPUS" ? CORPUS_OWNER_KEY : input.ownerUserId!;
  const language = input.language.trim().toLowerCase().slice(0, 20) || "und";
  const contentHash = contentHashOf(input.cues);
  const key = { videoId_source_language_ownerKey: { videoId, source: input.source, language, ownerKey } };
  const existing = await db.transcript.findUnique({ where: key, select: { id: true, contentHash: true, _count: { select: { chunks: true } } } });
  if (existing?.contentHash === contentHash) return { stored: false, chunks: existing._count.chunks, transcriptId: existing.id, reason: "unchanged" };

  const chunks: Chunk[] = chunkCues(input.cues);
  const t = await db.$transaction(async (tx) => {
    if (existing) await tx.transcript.delete({ where: { id: existing.id } }); // chunks cascade
    return tx.transcript.create({
      data: {
        videoId,
        source: input.source,
        visibility: input.visibility,
        ownerUserId: input.visibility === "PRIVATE" ? input.ownerUserId : null,
        ownerKey,
        connectionId: input.connectionId,
        providerTrackId: input.providerTrackId,
        language,
        trackKind: input.trackKind,
        isAutoGenerated: input.isAutoGenerated,
        contentHash,
        chunks: { createMany: { data: chunks.map((c) => ({ idx: c.idx, startSec: c.startSec, endSec: c.endSec, text: c.text })) } },
      },
      select: { id: true, chunks: { select: { id: true } } },
    });
  });
  await enqueue.embed("chunk", t.chunks.map((c) => c.id));
  if (input.visibility === "CORPUS") {
    await db.video.update({ where: { id: videoId }, data: { hasTranscript: true } });
    await setTranscriptStatus([videoId], "AVAILABLE", `transcript:${input.source}`);
    await enqueue.topics([videoId]);
  }
  log().info({ videoId, chunks: chunks.length, source: input.source, visibility: input.visibility }, "transcript stored");
  return { stored: true, chunks: chunks.length, transcriptId: t.id };
}

/** Worker entry: fetch from one provider candidate and store. Failures never fail the video's metadata collection. */
export async function fetchAndStore(videoId: string, providerName: string, connectionId?: string): Promise<StoreResult & { provider: string }> {
  const video = await db.video.findUnique({ where: { id: videoId }, select: { id: true, youtubeId: true, captionFlag: true, channel: { select: { youtubeId: true } } } });
  if (!video) throw notFound("Video");
  const provider = providerByName(providerName);
  if (!provider) throw new AppError("VALIDATION_ERROR", `Unknown transcript provider ${providerName}`);
  const pv: ProviderVideo = { id: video.id, youtubeId: video.youtubeId, channelYoutubeId: video.channel.youtubeId, captionFlag: video.captionFlag };
  const eligible = (await provider.candidates(pv)).some((c) => c.connectionId === connectionId);
  if (!eligible) return { stored: false, chunks: 0, reason: "empty", provider: provider.name };
  const fetched = await provider.fetch(pv, { provider: provider.name, connectionId });
  if (!fetched) {
    if (provider.name !== "OWNER_CAPTIONS") await setTranscriptStatus([video.id], "NOT_AVAILABLE", `transcript:${provider.name}`);
    return { stored: false, chunks: 0, reason: "empty", provider: provider.name };
  }
  const r = await storeTranscript(video.id, { source: provider.name, ...fetched });
  return { ...r, provider: provider.name };
}

/** Corpus-level status for videos with no shared provider: only a user upload can add a (private) transcript. */
export async function markTranscriptsUnavailable(videos: { id: string; captionFlag: boolean | null }[]) {
  const noTracks = videos.filter((v) => v.captionFlag === false).map((v) => v.id);
  const needUpload = videos.filter((v) => v.captionFlag !== false).map((v) => v.id);
  await setTranscriptStatus(noTracks, "NOT_AVAILABLE", "youtube:contentDetails.caption", "YouTube reports no caption tracks");
  await setTranscriptStatus(needUpload, "REQUIRES_USER_UPLOAD", "policy", "Public captions are not available through the official API; owner captions or an upload are required");
}

// ── User uploads ───────────────────────────────────────────────────────────

export const MAX_UPLOAD_CHARS = 2_000_000;

/** User upload (.vtt/.srt/.txt): private to the uploader, one record per (video, language, uploader). */
export async function uploadTranscript(videoId: string, text: string, opts: { filename?: string; language?: string; userId: string }) {
  if (text.length > MAX_UPLOAD_CHARS) throw new AppError("VALIDATION_ERROR", "Transcript too large (max 2 MB)");
  if (opts.filename && !/\.(vtt|srt|txt)$/i.test(opts.filename)) throw new AppError("VALIDATION_ERROR", "Upload a .vtt, .srt or .txt file");
  const cues = parseTranscript(text, opts.filename);
  if (!cues.length) throw new AppError("VALIDATION_ERROR", "No transcript text found in upload");
  const r = await storeTranscript(videoId, {
    source: "USER_UPLOAD",
    visibility: "PRIVATE",
    ownerUserId: opts.userId,
    language: opts.language ?? "en",
    trackKind: "UPLOADED",
    isAutoGenerated: false,
    cues,
  });
  return { ...r, cues: cues.length, tokens: cues.reduce((a, c) => a + estimateTokens(c.text), 0), visibility: "PRIVATE" as const };
}

/** Owners may delete their own transcripts (uploads or owner captions). Corpus transcripts cannot be deleted by users. */
export async function deleteTranscript(transcriptId: string, viewer: Viewer) {
  if (!viewer.userId) throw notFound("Transcript");
  const t = await db.transcript.findFirst({ where: { id: transcriptId, visibility: "PRIVATE", ownerUserId: viewer.userId }, select: { id: true } });
  if (!t) throw notFound("Transcript"); // 404 rather than 403: don't reveal other users' records
  await db.transcript.delete({ where: { id: t.id } });
  return { deleted: true };
}

// ── Reads ──────────────────────────────────────────────────────────────────

export interface TranscriptTrack {
  id: string;
  source: TranscriptSource;
  visibility: TranscriptVisibility;
  language: string;
  trackKind: TranscriptKind;
  isAutoGenerated: boolean;
  fetchedAt: Date;
  mine: boolean;
  chunks: number;
}

export async function listTracks(videoId: string, viewer: Viewer): Promise<TranscriptTrack[]> {
  const rows = await db.transcript.findMany({
    where: { videoId, ...visibleWhere(viewer) },
    orderBy: [{ fetchedAt: "desc" }],
    select: { id: true, source: true, visibility: true, language: true, trackKind: true, isAutoGenerated: true, fetchedAt: true, ownerUserId: true, _count: { select: { chunks: true } } },
  });
  return rows
    .map((r) => ({ id: r.id, source: r.source, visibility: r.visibility, language: r.language, trackKind: r.trackKind, isAutoGenerated: r.isAutoGenerated, fetchedAt: r.fetchedAt, mine: Boolean(viewer.userId && r.ownerUserId === viewer.userId), chunks: r._count.chunks }))
    .sort((a, b) => Number(b.mine) - Number(a.mine) || Number(a.isAutoGenerated) - Number(b.isAutoGenerated));
}

/** The viewer's preferred readable transcript (own > manual > ASR), or a specific one they can read. */
export async function getTranscript(videoId: string, viewer: Viewer, transcriptId?: string) {
  const tracks = await listTracks(videoId, viewer);
  const chosen = transcriptId ? tracks.find((t) => t.id === transcriptId) : tracks[0];
  if (!chosen) return null;
  const t = await db.transcript.findUniqueOrThrow({
    where: { id: chosen.id },
    select: { video: { select: { youtubeId: true } }, chunks: { orderBy: { idx: "asc" }, select: { id: true, idx: true, startSec: true, endSec: true, text: true } } },
  });
  return {
    id: chosen.id,
    source: chosen.source,
    visibility: chosen.visibility,
    language: chosen.language,
    trackKind: chosen.trackKind,
    isAutoGenerated: chosen.isAutoGenerated,
    fetchedAt: chosen.fetchedAt,
    mine: chosen.mine,
    tracks,
    chunks: t.chunks.map((c) => ({ ...c, url: timestampUrl(t.video.youtubeId, c.startSec) })),
  };
}

/** First chunks of the shared-corpus transcript, for shared derived data (topics, AI). Never private text. */
export async function corpusTranscriptText(videoId: string, take: number): Promise<string[]> {
  const t = await db.transcript.findFirst({ where: { videoId, ...corpusWhere() }, orderBy: { fetchedAt: "desc" }, select: { chunks: { orderBy: { idx: "asc" }, take, select: { text: true } } } });
  return t?.chunks.map((c) => c.text) ?? [];
}

