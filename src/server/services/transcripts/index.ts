/**
 * Transcripts: one optional field group of a video's unified record (never a collection objective of its own).
 *
 * Identity: (video, source, language, owner). Visibility:
 *  • PRIVATE — owner captions (authorizing user) and user uploads (uploader). Only that user can read them; they never
 *    feed shared derived data (topics, AI extraction, global search, graph attributes).
 *  • CORPUS  — the shared demo corpus (fixture transcripts), served only in fixture mode.
 * Every read path goes through `visibleWhere` / `visibleSql`.
 */
