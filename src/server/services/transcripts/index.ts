/** The first provider that can supply a transcript for free (no speculative quota spend). */
export async function autoProviderFor(v: ProviderVideo): Promise<string | null> {
  for (const p of PROVIDERS) if (await p.isAvailable(v)) return p.name;
  return null;
}

const SOURCE: Record<string, TranscriptSource> = {
  OWNER_CAPTIONS: "OWNER_CAPTIONS",
  USER_UPLOAD: "USER_UPLOAD",
  FIXTURE: "FIXTURE",
  THIRD_PARTY: "THIRD_PARTY",
};

export interface StoreResult {
  stored: boolean;
  chunks: number;
  reason?: "unchanged" | "empty";
}

/** Persist cues → chunks. Skips unchanged re-imports via contentHash. Enqueues chunk embeddings + topic refresh. */
export async function storeTranscript(
  videoId: string,
  input: { source: TranscriptSource; language: string; isAutoGenerated: boolean; cues: Cue[]; uploadedById?: string },
): Promise<StoreResult> {
  if (!input.cues.length) return { stored: false, chunks: 0, reason: "empty" };
  const contentHash = createHash("sha256").update(input.cues.map((c) => `${c.start}|${c.text}`).join("\n")).digest("hex");
  const existing = await db.transcript.findUnique({ where: { videoId }, select: { id: true, contentHash: true, _count: { select: { chunks: true } } } });
  if (existing?.contentHash === contentHash) return { stored: false, chunks: existing._count.chunks, reason: "unchanged" };

  const chunks: Chunk[] = chunkCues(input.cues);
  const chunkIds = await db.$transaction(async (tx) => {
    if (existing) await tx.transcript.delete({ where: { id: existing.id } });
    const t = await tx.transcript.create({
      data: {
        videoId,
        source: input.source,
        language: input.language,
        isAutoGenerated: input.isAutoGenerated,
        contentHash,
        uploadedById: input.uploadedById,
        chunks: { createMany: { data: chunks.map((c) => ({ idx: c.idx, startSec: c.startSec, endSec: c.endSec, text: c.text })) } },
      },
      select: { chunks: { select: { id: true } } },
    });
    await tx.video.update({ where: { id: videoId }, data: { hasTranscript: true } });
    return t.chunks.map((c) => c.id);
  });
  await enqueue.embed("chunk", chunkIds);
  await enqueue.topics([videoId]);
  log().info({ videoId, chunks: chunks.length, source: input.source }, "transcript stored");
  return { stored: true, chunks: chunks.length };
}

/** Worker entry: fetch from a provider and store. */
export async function fetchAndStore(videoId: string, providerName: string): Promise<StoreResult & { provider: string }> {
  const video = await db.video.findUnique({ where: { id: videoId }, select: { id: true, youtubeId: true, channel: { select: { youtubeId: true } } } });
  if (!video) throw notFound("Video");
  const provider = providerByName(providerName);
  if (!provider) throw new AppError("VALIDATION_ERROR", `Unknown transcript provider ${providerName}`);
  const pv = { id: video.id, youtubeId: video.youtubeId, channelYoutubeId: video.channel.youtubeId };
  if (!(await provider.isAvailable(pv))) return { stored: false, chunks: 0, reason: "empty", provider: provider.name };
  const fetched = await provider.fetch(pv);
  if (!fetched) return { stored: false, chunks: 0, reason: "empty", provider: provider.name };
  const r = await storeTranscript(video.id, { source: SOURCE[provider.name]!, ...fetched });
  return { ...r, provider: provider.name };
}

/** User upload (.vtt/.srt/.txt). */
export async function uploadTranscript(videoId: string, text: string, opts: { filename?: string; language?: string; userId: string }) {
  if (text.length > 2_000_000) throw new AppError("VALIDATION_ERROR", "Transcript too large (max 2 MB)");
  const cues = parseTranscript(text, opts.filename);
  if (!cues.length) throw new AppError("VALIDATION_ERROR", "No transcript text found in upload");
  const r = await storeTranscript(videoId, { source: "USER_UPLOAD", language: opts.language ?? "en", isAutoGenerated: false, cues, uploadedById: opts.userId });
  return { ...r, cues: cues.length, tokens: cues.reduce((a, c) => a + estimateTokens(c.text), 0) };
}

export async function getTranscript(videoId: string) {
  const t = await db.transcript.findUnique({
    where: { videoId },
    select: {
      source: true,
      language: true,
      isAutoGenerated: true,
      fetchedAt: true,
      video: { select: { youtubeId: true } },
      chunks: { orderBy: { idx: "asc" }, select: { id: true, idx: true, startSec: true, endSec: true, text: true } },
    },
  });
  if (!t) return null;
  return {
    source: t.source,
    language: t.language,
    isAutoGenerated: t.isAutoGenerated,
    fetchedAt: t.fetchedAt,
    chunks: t.chunks.map((c) => ({ ...c, url: timestampUrl(t.video.youtubeId, c.startSec) })),
  };
}
