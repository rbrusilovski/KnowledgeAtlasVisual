import { db } from "@/server/db";
import { env } from "@/server/env";
import { decrypt } from "@/server/crypto";
import { youtube, youtubeMode } from "@/server/youtube";
import { fixtureTranscript } from "@/server/youtube/fixture";
import { parseVtt, type Cue } from "./parse";

export interface ProviderVideo {
  id: string;
  youtubeId: string;
  channelYoutubeId: string;
}

export interface FetchedTranscript {
  language: string;
  isAutoGenerated: boolean;
  cues: Cue[];
}

export interface TranscriptProvider {
  readonly name: "OWNER_CAPTIONS" | "USER_UPLOAD" | "FIXTURE" | "THIRD_PARTY";
  /** Must be cheap and must not spend quota. */
  isAvailable(video: ProviderVideo): Promise<boolean>;
  fetch(video: ProviderVideo): Promise<FetchedTranscript | null>;
}

/** Captions for channels the user has connected via Google OAuth (youtube.force-ssl). 50 + 200 units. */
export const ownerCaptionsProvider: TranscriptProvider = {
  name: "OWNER_CAPTIONS",
  async isAvailable(v) {
    if (!env.FEATURE_YOUTUBE_OAUTH || youtubeMode() !== "live") return false;
    const conn = await db.youTubeConnection.findFirst({ where: { channelIds: { has: v.channelYoutubeId } }, select: { id: true } });
    return Boolean(conn);
  },
  async fetch(v) {
    const conn = await db.youTubeConnection.findFirst({ where: { channelIds: { has: v.channelYoutubeId } } });
    if (!conn) return null;
    const token = decrypt(conn.accessTokenEnc);
    const tracks = await youtube.listCaptions(v.youtubeId, token);
    const track = tracks.find((t) => !t.isAutoGenerated && t.language.startsWith("en")) ?? tracks.find((t) => t.language.startsWith("en")) ?? tracks[0];
    if (!track) return null;
    const vtt = await youtube.downloadCaption(track.id, token);
    return { language: track.language, isAutoGenerated: track.isAutoGenerated, cues: parseVtt(vtt) };
  },
};

/** User uploads are pushed through the API; never auto-fetched. */
export const userUploadProvider: TranscriptProvider = {
  name: "USER_UPLOAD",
  async isAvailable() {
    return false;
  },
  async fetch() {
    return null;
  },
};

export const fixtureProvider: TranscriptProvider = {
  name: "FIXTURE",
  async isAvailable(v) {
    return youtubeMode() === "fixture" && Boolean(fixtureTranscript(v.youtubeId));
  },
  async fetch(v) {
    const vtt = fixtureTranscript(v.youtubeId);
    if (!vtt) return null;
    return { language: "en", isAutoGenerated: true, cues: parseVtt(vtt) };
  },
};

/**
 * Third-party transcript adapter — INTERFACE ONLY, disabled by default (TRANSCRIPT_THIRD_PARTY_ENABLED=false).
 * Operators who enable it must plug in a compliant implementation and are responsible for YouTube ToS compliance.
 * Atlas deliberately ships no HTML scraper.
 */
export interface ThirdPartyTranscriptAdapter {
  fetch(youtubeVideoId: string): Promise<FetchedTranscript | null>;
}
let thirdPartyAdapter: ThirdPartyTranscriptAdapter | null = null;
export function registerThirdPartyAdapter(a: ThirdPartyTranscriptAdapter) {
  thirdPartyAdapter = a;
}
export const thirdPartyProvider: TranscriptProvider = {
  name: "THIRD_PARTY",
  async isAvailable() {
    return env.TRANSCRIPT_THIRD_PARTY_ENABLED && thirdPartyAdapter !== null;
  },
  async fetch(v) {
    return env.TRANSCRIPT_THIRD_PARTY_ENABLED && thirdPartyAdapter ? thirdPartyAdapter.fetch(v.youtubeId) : null;
  },
};

export const PROVIDERS: TranscriptProvider[] = [ownerCaptionsProvider, fixtureProvider, thirdPartyProvider, userUploadProvider];

export function providerByName(name: string): TranscriptProvider | undefined {
  return PROVIDERS.find((p) => p.name === name);
}
