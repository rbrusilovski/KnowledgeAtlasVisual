import { db, type TranscriptKind, type TranscriptSource, type TranscriptVisibility } from "@/server/db";
import { env } from "@/server/env";
import { accessTokenFor } from "@/server/youtube/oauth";
import { youtube, youtubeMode } from "@/server/youtube";
import { fixtureTranscript } from "@/server/youtube/fixture";
import { parseVtt, type Cue } from "./parse";

export interface ProviderVideo {
  id: string;
  youtubeId: string;
  channelYoutubeId: string;
  /** contentDetails.caption — whether YouTube reports caption tracks exist. false ⇒ never spend caption quota. */
  captionFlag?: boolean | null;
}

/** Who a fetched transcript belongs to. Owner captions → the authorizing user; fixtures → the shared demo corpus. */
export interface TranscriptOwnership {
  visibility: TranscriptVisibility;
  ownerUserId?: string;
  connectionId?: string;
}

export interface FetchedTranscript extends TranscriptOwnership {
  language: string;
  isAutoGenerated: boolean;
  trackKind: TranscriptKind;
  providerTrackId?: string;
  cues: Cue[];
}

export type ProviderName = Exclude<TranscriptSource, "USER_UPLOAD">;

/** One concrete fetch a provider can perform (e.g. one per authorizing YouTube connection). */
export interface TranscriptCandidate {
  provider: ProviderName;
  connectionId?: string;
}

export interface TranscriptProvider {
  readonly name: ProviderName;
  /** Must be cheap and must not spend quota (DB/fixture lookups only). */
  candidates(video: ProviderVideo): Promise<TranscriptCandidate[]>;
  fetch(video: ProviderVideo, candidate: TranscriptCandidate): Promise<FetchedTranscript | null>;
}

/**
 * Official owner captions (captions.list 50 + captions.download 200 units) for channels a user connected via Google
 * OAuth. Only the authorizing account's own channels are eligible; the result is PRIVATE to that user and tied to the
 * connection, so revoking the connection deletes it. One preferred track per video bounds cost (manual > ASR, English
 * first); other languages can be added by the owner later.
 */
export const ownerCaptionsProvider: TranscriptProvider = {
  name: "OWNER_CAPTIONS",
  async candidates(v) {
    if (!env.FEATURE_YOUTUBE_OAUTH || youtubeMode() !== "live") return [];
    if (v.captionFlag === false) return []; // YouTube reports no caption tracks: don't spend 50 units to confirm.
    const conns = await db.youTubeConnection.findMany({ where: { channelIds: { has: v.channelYoutubeId } }, select: { id: true }, orderBy: { createdAt: "asc" } });
    return conns.map((c) => ({ provider: "OWNER_CAPTIONS" as const, connectionId: c.id }));
  },
  async fetch(v, c) {
    if (!c.connectionId) return null;
    const conn = await db.youTubeConnection.findUnique({ where: { id: c.connectionId }, select: { id: true, userId: true, channelIds: true } });
    // Re-check ownership at fetch time: the connection may have been revoked or lost the channel since enqueue.
    if (!conn || !conn.channelIds.includes(v.channelYoutubeId)) return null;
    const token = await accessTokenFor(conn.id);
    const tracks = await youtube.listCaptions(v.youtubeId, token);
    const track = tracks.find((t) => !t.isAutoGenerated && t.language.startsWith("en")) ?? tracks.find((t) => !t.isAutoGenerated) ?? tracks.find((t) => t.language.startsWith("en")) ?? tracks[0];
    if (!track) return null;
    const vtt = await youtube.downloadCaption(track.id, token);
    return {
      language: track.language,
      isAutoGenerated: track.isAutoGenerated,
      trackKind: track.isAutoGenerated ? "ASR" : "MANUAL",
      providerTrackId: track.id,
      cues: parseVtt(vtt),
      visibility: "PRIVATE",
      ownerUserId: conn.userId,
      connectionId: conn.id,
    };
  },
};

/** Synthetic transcripts for the fictional demo dataset — shared corpus, served only in fixture mode. */
export const fixtureProvider: TranscriptProvider = {
  name: "FIXTURE",
  async candidates(v) {
    return youtubeMode() === "fixture" && fixtureTranscript(v.youtubeId) ? [{ provider: "FIXTURE" }] : [];
  },
  async fetch(v) {
    const vtt = fixtureTranscript(v.youtubeId);
    if (!vtt) return null;
    return { language: "en", isAutoGenerated: true, trackKind: "FIXTURE", cues: parseVtt(vtt), visibility: "CORPUS" };
  },
};

/**
 * Third-party transcript adapter — INTERFACE ONLY, disabled by default (TRANSCRIPT_THIRD_PARTY_ENABLED=false).
 * Operators who enable it must plug in a compliant implementation and are responsible for YouTube ToS compliance.
 * Atlas deliberately ships no HTML scraper and no paid provider.
 */
export interface ThirdPartyTranscriptAdapter {
  fetch(youtubeVideoId: string): Promise<Omit<FetchedTranscript, keyof TranscriptOwnership | "trackKind"> | null>;
}
let thirdPartyAdapter: ThirdPartyTranscriptAdapter | null = null;
export function registerThirdPartyAdapter(a: ThirdPartyTranscriptAdapter) {
  thirdPartyAdapter = a;
}
export const thirdPartyProvider: TranscriptProvider = {
  name: "THIRD_PARTY",
  async candidates() {
    return env.TRANSCRIPT_THIRD_PARTY_ENABLED && thirdPartyAdapter ? [{ provider: "THIRD_PARTY" }] : [];
  },
  async fetch(v) {
    if (!env.TRANSCRIPT_THIRD_PARTY_ENABLED || !thirdPartyAdapter) return null;
    const r = await thirdPartyAdapter.fetch(v.youtubeId);
    // Never shared by default: an operator-supplied provider stays private until a policy decision says otherwise.
    return r && { ...r, trackKind: r.isAutoGenerated ? "ASR" : "MANUAL", visibility: "PRIVATE" };
  },
};

/** User uploads arrive through the API (services/transcripts.uploadTranscript) and are never auto-fetched. */
export const PROVIDERS: TranscriptProvider[] = [ownerCaptionsProvider, fixtureProvider, thirdPartyProvider];

export function providerByName(name: string): TranscriptProvider | undefined {
  return PROVIDERS.find((p) => p.name === name);
}
