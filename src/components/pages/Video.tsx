interface VideoDetail {
  id: string;
  youtubeId: string;
  nodeId: string;
  title: string;
  description: string;
  publishedAt: string;
  durationSec: number | null;
  tags: string[];
  viewCount: number | null;
  likeCount: number | null;
  commentCount: number | null;
  thumbnailUrl: string | null;
  hasTranscript: boolean;
  url: string;
  statistics: Record<"views" | "likes" | "comments", { value: number | null; availability: string; asOf: string | null }>;
  coverage: { complete: boolean; groups: { group: string; status: string; reason: string | null; required: boolean; lastSuccessAt: string | null }[] };
  channel: { nodeId: string; title: string; youtubeId: string; thumbnailUrl: string | null; subscriberCount: number | null };
  topics: { nodeId: string; label: string; weight: number; source: string; materialized: boolean }[];
  transcript: { source: string; language: string; isAutoGenerated: boolean; chunks: number } | null;
  ai: { enabled: boolean; extraction: { output: { summary: string; topics: { label: string }[]; entities: { name: string; type: string }[]; claims: string[] }; model: string } | null };
}
interface Chunk {
  id: string;
  idx: number;
  startSec: number;
  endSec: number;
  text: string;
  url: string;
}
interface TrackDTO {
  id: string;
  source: string;
  visibility: "PRIVATE" | "CORPUS";
  language: string;
  isAutoGenerated: boolean;
  mine: boolean;
}
interface TranscriptDTO {
  id: string;
  source: string;
  visibility: "PRIVATE" | "CORPUS";
  mine: boolean;
  language: string;
  isAutoGenerated: boolean;
  tracks: TrackDTO[];
  chunks: Chunk[];
  hits?: (Chunk & { rank: number })[];
}

export function VideoPage({ id }: { id: string }) {
  const q = useQuery({ queryKey: ["video", id], queryFn: () => api.get<VideoDetail>(`/api/videos/${id}`) });
  const sp = useSearchParams();
  const router = useRouter();
  const t = sp.get("t") ? Number(sp.get("t")) : null;
  const me = useMe();
  const quota = useQuota();
  const [playing, setPlaying] = useState(false);
  const seek = (sec: number) => {
    const u = new URL(window.location.href);
    u.searchParams.set("t", String(Math.floor(sec)));
    router.replace(`${u.pathname}${u.search}`, { scroll: false });
    setPlaying(true);
  };
  if (q.isLoading)
    return (
      <Page wide>
        <PanelSkeleton rows={8} />
      </Page>
    );
  if (q.error)
    return (
      <Page>
        <ErrorState error={q.error} onRetry={() => q.refetch()} />
      </Page>
    );
  const v = q.data!;
  const demo = quota.data?.mode === "fixture";
  return (
    <Page wide>
      <div className="grid grid-cols-1 gap-6 lg:grid-cols-[1fr_400px]">
        <div className="min-w-0">
          <div className="relative aspect-video overflow-hidden rounded-panel border border-border bg-black">
            {playing && !demo ? (
              <iframe
                key={t ?? 0}
                src={`https://www.youtube-nocookie.com/embed/${v.youtubeId}?autoplay=1&start=${t ?? 0}&rel=0`}
                title={v.title}
                allow="autoplay; encrypted-media; picture-in-picture"
                allowFullScreen
                className="absolute inset-0 size-full"
              />
            ) : (
              <button onClick={() => setPlaying(true)} className="group absolute inset-0" aria-label={demo ? "Demo video (no playback)" : "Load YouTube player"}>
                <img src={v.thumbnailUrl ?? `/api/placeholder/thumb/${v.youtubeId}`} alt="" className="size-full object-cover opacity-80 transition-opacity group-hover:opacity-100" />
                <span className="absolute left-1/2 top-1/2 flex size-14 -translate-x-1/2 -translate-y-1/2 items-center justify-center rounded-full bg-black/70 text-white ring-1 ring-white/20 group-hover:bg-accent-500">
                  <Play className="size-6 fill-current" />
                </span>
                {demo && playing ? <span className="absolute inset-x-0 bottom-0 bg-black/70 p-2 text-center text-xs text-text-2">Fictional demo video — there is nothing to play on YouTube.</span> : null}
                {t !== null ? <span className="num absolute bottom-3 right-3 rounded bg-black/70 px-1.5 py-0.5 text-xs text-white">▶ {fmtTimestamp(t)}</span> : null}
              </button>
            )}
          </div>
          <p className="mt-1 text-[11px] text-text-3">Player loads from youtube-nocookie.com only when you click.</p>
          <h1 className="mt-3 text-xl leading-snug text-text-1">{v.title}</h1>
          <div className="mt-2 flex flex-wrap items-center gap-3">
            <Link href={`/channels/${v.channel.youtubeId}`} className="flex items-center gap-2 text-sm text-text-2 hover:text-text-1">
              <img src={v.channel.thumbnailUrl ?? ""} alt="" className="size-6 rounded-full border border-border" />
              {v.channel.title}
            </Link>
            <span className="text-xs text-text-3">{fmtDate(v.publishedAt)}</span>
            <div className="ml-auto flex gap-2">
              <AddToCollectionMenu nodeIds={[v.nodeId]} />
              <Button size="sm" variant="ghost" asChild>
                <Link href={`/atlas?mode=local&focus=${encodeURIComponent(v.nodeId)}&depth=2`}>
                  <Network /> Atlas
                </Link>
              </Button>
              <Button size="sm" variant="ghost" asChild>
                <a href={t !== null ? `${v.url}&t=${t}s` : v.url} target="_blank" rel="noopener noreferrer">
                  <ExternalLink /> YouTube
                </a>
              </Button>
            </div>
          </div>
          <div className="mt-4 grid grid-cols-4 gap-2">
            <Stat label="Views" value={statValue(v.statistics.views)} />
            <Stat label="Likes" value={statValue(v.statistics.likes)} />
            <Stat label="Comments" value={statValue(v.statistics.comments)} />
            <Stat label="Length" value={fmtDuration(v.durationSec)} />
          </div>
          {v.statistics.views.asOf ? <p className="mt-1 text-[11px] text-text-3">Statistics as of {new Date(v.statistics.views.asOf).toLocaleString()}</p> : null}
          <CoverageList v={v} />
          {v.topics.length ? (
            <div className="mt-4 flex flex-wrap gap-1.5">
              {v.topics.filter((x) => x.materialized).map((x) => (
                <Link key={x.nodeId} href={`/atlas?mode=local&focus=${encodeURIComponent(x.nodeId)}&depth=2`}>
                  <Badge tone={x.source === "ai" ? "accent" : "neutral"}>{x.label}</Badge>
                </Link>
              ))}
            </div>
          ) : null}
          <AiSummary v={v} canRun={Boolean(me.data)} />
          <p className="mt-4 whitespace-pre-line text-sm leading-relaxed text-text-2">
            <Linkified text={v.description} />
          </p>
          <p className="mt-4 text-[11px] text-text-3">Video data from the YouTube Data API.</p>
        </div>
        <TranscriptPanel video={v} activeSec={t} onSeek={seek} signedIn={Boolean(me.data)} authPending={me.isPending} />
      </div>
    </Page>
  );
}

/** Hidden/disabled statistics are shown as such — never as 0. */
function statValue(s: { value: number | null; availability: string }) {
  if (s.value !== null) return fmtCompact(s.value);
  return s.availability === "HIDDEN" ? "hidden" : s.availability === "DISABLED_OR_HIDDEN" ? "off" : s.availability === "UNAVAILABLE" ? "n/a" : "—";
}

const COVERAGE_TEXT: Record<string, string> = {
  PRESENT: "collected",
  UNAVAILABLE: "not available",
  NOT_APPLICABLE: "n/a",
  STALE: "refresh due",
  NOT_RETURNED: "not returned",
  NOT_REQUESTED: "not requested",
  ERROR: "error",
  EXPIRED: "expired",
};

function CoverageList({ v }: { v: VideoDetail }) {
  return (
    <details className="mt-3 rounded-control border border-border bg-bg-1 px-3 py-2 text-xs" data-testid="video-coverage">
      <summary className="cursor-pointer text-text-2">
        Collected data · {v.coverage.complete ? "complete" : "incomplete"} <span className="text-text-3">(transcripts are optional)</span>
      </summary>
      <ul className="mt-2 grid grid-cols-2 gap-x-4 gap-y-1">
        {v.coverage.groups.map((g) => (
          <li key={g.group} className="flex justify-between gap-2" title={g.reason ?? undefined}>
            <span className="text-text-3">{g.group.replace(/_/g, " ").toLowerCase()}</span>
            <span className={g.status === "PRESENT" ? "text-success" : g.status === "STALE" || g.status === "NOT_RETURNED" ? "text-warning" : g.status === "ERROR" ? "text-danger" : "text-text-2"}>{COVERAGE_TEXT[g.status] ?? g.status}</span>
          </li>
        ))}
      </ul>
    </details>
  );
}

function AiSummary({ v, canRun }: { v: VideoDetail; canRun: boolean }) {
  const qc = useQueryClient();
  const [busy, setBusy] = useState(false);
  if (!v.ai.enabled) return null;
  const ex = v.ai.extraction;
  return (
    <div className="mt-4 rounded-card border border-accent-500/25 bg-accent-500/5 p-3">
      <div className="mb-1 flex items-center gap-2 text-xs font-medium text-accent-300">
        <Sparkles className="size-3.5" /> AI summary
        {ex ? <span className="text-text-3">· {ex.model}</span> : null}
      </div>
      {ex ? (
        <div className="space-y-2 text-sm text-text-2">
          <p>{ex.output.summary}</p>
          {ex.output.claims.length ? (
            <ul className="list-disc pl-5 text-[13px]">
              {ex.output.claims.map((c) => <li key={c}>{c}</li>)}
            </ul>
          ) : null}
        </div>
      ) : canRun ? (
        <Button
          size="sm"
          variant="secondary"
          disabled={busy}
          onClick={async () => {
            setBusy(true);
            try {
              await api.post(`/api/videos/${v.youtubeId}/extract`);
              await qc.invalidateQueries({ queryKey: ["video", v.youtubeId] });
            } catch (e) {
              toast.error(e instanceof Error ? e.message : "Extraction failed");
            } finally {
              setBusy(false);
            }
          }}
        >
          {busy ? "Summarizing…" : "Generate summary, topics & claims"}
        </Button>
      ) : (
        <p className="text-xs text-text-3">Sign in to generate an AI summary.</p>
      )}
    </div>
  );
}

function TranscriptPanel({ video, activeSec, onSeek, signedIn, authPending }: { video: VideoDetail; activeSec: number | null; onSeek: (s: number) => void; signedIn: boolean; authPending: boolean }) {
  const [q, setQ] = useState("");
  const [dq, setDq] = useState("");
  const [upload, setUpload] = useState(false);
  const [trackId, setTrackId] = useState<string | undefined>();
  const qc = useQueryClient();
  useEffect(() => {
    const t = setTimeout(() => setDq(q.trim()), 200);
    return () => clearTimeout(t);
  }, [q]);
  // Transcripts require sign-in (the route is auth-required), so signed-out viewers never request them.
  const r = useQuery({ queryKey: ["transcript", video.youtubeId, dq, trackId], enabled: signedIn, queryFn: () => api.getWithMeta<TranscriptDTO | null>(`/api/videos/${video.youtubeId}/transcript`, { q: dq || undefined, transcriptId: trackId }) });
  const remove = async (id: string) => {
    try {
      await api.del(`/api/videos/${video.youtubeId}/transcript?transcriptId=${encodeURIComponent(id)}`);
      toast.success("Your transcript was deleted");
      setTrackId(undefined);
      await qc.invalidateQueries({ queryKey: ["transcript", video.youtubeId] });
    } catch (e) {
      toast.error(e instanceof Error ? e.message : "Could not delete");
    }
  };
  const listRef = useRef<HTMLOListElement>(null);
  const data = r.data?.data ?? null;
  const hitIds = useMemo(() => new Set(data?.hits?.map((h) => h.id)), [data?.hits]);
  // Last chunk starting at or before the (whole-second) timestamp; chunks overlap, so prefer the latest start.
  const activeIdx = activeSec === null || !data ? -1 : data.chunks.reduce((best, c, i) => (Math.floor(c.startSec) <= activeSec ? i : best), activeSec !== null && data.chunks.length ? 0 : -1);
  useEffect(() => {
    if (activeIdx < 0) return;
    listRef.current?.querySelector(`[data-idx="${activeIdx}"]`)?.scrollIntoView({ block: "center", behavior: "smooth" });
  }, [activeIdx]);
  return (
    <aside className="flex max-h-[calc(100dvh-140px)] min-h-96 flex-col rounded-panel border border-border bg-bg-1">
      <div className="flex items-center justify-between border-b border-border px-3 py-2.5">
        <div className="text-sm text-text-1">Transcript</div>
        {data ? (
          <span className="flex items-center gap-1.5 text-xs text-text-3">
            {data.visibility === "PRIVATE" ? <Badge tone="accent" data-testid="transcript-private">Private · only you</Badge> : null}
            {data.source.toLowerCase().replace("_", " ")} · {data.language}
            {data.isAutoGenerated ? " · auto" : ""}
          </span>
        ) : null}
        {signedIn ? (
          <Button size="sm" variant="ghost" onClick={() => setUpload(true)}>
            <FileUp /> Upload
          </Button>
        ) : null}
      </div>
      {data && (data.tracks.length > 1 || data.mine) ? (
        <div className="flex items-center gap-2 border-b border-border px-3 py-1.5 text-xs">
          {data.tracks.length > 1 ? (
            <select value={data.id} onChange={(e) => setTrackId(e.target.value)} className="h-7 rounded-control border border-border bg-bg-2 px-1.5 text-text-1" aria-label="Transcript track">
              {data.tracks.map((t) => (
                <option key={t.id} value={t.id}>
                  {t.mine ? "Yours · " : ""}
                  {t.source.toLowerCase().replace("_", " ")} · {t.language}
                </option>
              ))}
            </select>
          ) : null}
          {data.mine ? (
            <Button size="sm" variant="ghost" className="ml-auto h-7" onClick={() => void remove(data.id)}>
              Delete mine
            </Button>
          ) : null}
        </div>
      ) : null}
      {data ? (
        <div className="border-b border-border p-2">
          <div className="relative">
            <Search className="absolute left-2 top-2 size-4 text-text-3" />
            <Input value={q} onChange={(e) => setQ(e.target.value)} placeholder="Search in transcript…" className="pl-8" aria-label="Search in transcript" data-testid="transcript-search" />
            {q ? <button className="absolute right-2 top-2 text-text-3" onClick={() => setQ("")} aria-label="Clear"><X className="size-4" /></button> : null}
          </div>
          {dq ? <div className="mt-1.5 px-1 text-xs text-text-3" aria-live="polite">{data.hits?.length ?? 0} matches</div> : null}
          {dq && data.hits?.length ? (
            <ul className="mt-1 max-h-40 space-y-1 overflow-y-auto" data-testid="transcript-hits">
              {data.hits.map((h) => (
                <li key={h.id}>
                  <button onClick={() => onSeek(h.startSec)} className="flex w-full gap-2 rounded-control px-1.5 py-1 text-left text-xs hover:bg-bg-3">
                    <span className="num shrink-0 text-accent-300">{fmtTimestamp(h.startSec)}</span>
                    <Highlight text={h.text} className="line-clamp-2 text-text-2" />
                  </button>
                </li>
              ))}
            </ul>
          ) : null}
        </div>
      ) : null}
      <div className="min-h-0 flex-1 overflow-y-auto p-2">
        {authPending || r.isLoading ? (
          <div className="space-y-2 p-2">{Array.from({ length: 8 }, (_, i) => <Skeleton key={i} className="h-10" />)}</div>
        ) : !signedIn ? (
          <EmptyState title="Sign in to view transcripts" body="Transcripts are only shown to signed-in users. Private uploads and owner captions stay visible only to their owner.">
            <Button asChild size="sm" variant="secondary" data-testid="transcript-signin">
              <Link href={`/signin?next=${encodeURIComponent(`/videos/${video.youtubeId}`)}`}>Sign in</Link>
            </Button>
          </EmptyState>
        ) : r.error ? (
          <ErrorState error={r.error} onRetry={() => r.refetch()} />
        ) : !data ? (
          <EmptyState title="No transcript available" body="The official API only exposes captions to the channel owner. Upload a .vtt, .srt or text transcript — it stays private to you and is searchable only by you. The video's other metadata is complete without one.">
            {signedIn ? (
              <Button size="sm" variant="secondary" onClick={() => setUpload(true)}>
                <FileUp /> Upload transcript
              </Button>
            ) : null}
          </EmptyState>
        ) : (
          <ol ref={listRef} className="space-y-1" data-testid="transcript-chunks">
            {data.chunks.map((c) => (
              <li key={c.id} data-idx={c.idx} data-active={c.idx === activeIdx || undefined} className={cn("flex items-start gap-2 rounded-control px-2 py-1.5 text-[13px] leading-relaxed", c.idx === activeIdx ? "bg-accent-500/15 ring-1 ring-accent-500/40" : hitIds.has(c.id) ? "bg-bg-3" : "")}>
                <button onClick={() => onSeek(c.startSec)} className="num shrink-0 pt-px text-xs text-accent-300 hover:underline" aria-label={`Jump to ${fmtTimestamp(c.startSec)}`}>
                  {fmtTimestamp(c.startSec)}
                </button>
                <span className="text-text-2">{c.text}</span>
              </li>
            ))}
          </ol>
        )}
      </div>
      {upload ? <UploadTranscript videoId={video.youtubeId} onClose={() => setUpload(false)} /> : null}
    </aside>
  );
}

function UploadTranscript({ videoId, onClose }: { videoId: string; onClose: () => void }) {
  const [text, setText] = useState("");
  const [filename, setFilename] = useState<string | undefined>();
  const [busy, setBusy] = useState(false);
  const qc = useQueryClient();
  return (
    <Dialog open onOpenChange={(o) => !o && onClose()}>
      <DialogContent title="Upload transcript" description="Paste or choose a .vtt, .srt or plain-text transcript (timestamps optional). It is private to you and replaces only your own earlier upload for this language.">
        <div className="space-y-3">
          <Input
            type="file"
            accept=".vtt,.srt,.txt,text/vtt,text/plain"
            className="h-auto py-1.5 file:mr-2 file:rounded file:border-0 file:bg-bg-3 file:px-2 file:text-text-1"
            onChange={async (e) => {
              const f = e.target.files?.[0];
              if (!f) return;
              if (f.size > 2_000_000) return toast.error("File is larger than 2 MB");
              setFilename(f.name);
              setText(await f.text());
            }}
            aria-label="Transcript file"
          />
          <Textarea value={text} onChange={(e) => setText(e.target.value)} placeholder={"WEBVTT\n\n00:00:01.000 --> 00:00:04.000\nHello…"} className="min-h-40 font-mono text-xs" aria-label="Transcript text" />
          <div className="flex justify-end gap-2">
            <Button variant="ghost" onClick={onClose}>Cancel</Button>
            <Button
              variant="primary"
              disabled={!text.trim() || busy}
              onClick={async () => {
                setBusy(true);
                try {
                  const r = await api.post<{ stored: boolean; chunks: number; reason?: string }>(`/api/videos/${videoId}/transcript`, { text, filename });
                  toast.success(r.stored ? `Transcript stored · ${r.chunks} chunks` : "Transcript unchanged");
                  await qc.invalidateQueries({ queryKey: ["transcript", videoId] });
                  await qc.invalidateQueries({ queryKey: ["video", videoId] });
                  onClose();
                } catch (e) {
                  toast.error(e instanceof Error ? e.message : "Upload failed");
                } finally {
                  setBusy(false);
                }
              }}
            >
              {busy ? "Uploading…" : "Upload"}
            </Button>
          </div>
        </div>
      </DialogContent>
    </Dialog>
  );
}
